import { patch } from "@web/core/utils/patch";
import { PaymentScreen } from "@point_of_sale/app/screens/payment_screen/payment_screen";
import { onMounted } from "@odoo/owl";

patch(PaymentScreen.prototype, {
    setup() {
        super.setup(...arguments);
        onMounted(() => {
            if (this.pos.config.useFiscalPrinter && !this.pos.data.network.offline) {
                const order = this.pos.getOrder();
                const totalToPay = this.pos.formatCurrency(order.totalDue);
                this.pos.ticketPrinter.fiscalPrinter.displayText(`To Pay: ${totalToPay}`);
            }
        });
    },
    shouldDownloadInvoice() {
        if (this.pos.config.useFiscalPrinter) {
            // Never print invoice generated by odoo. It will be printed by the fiscal printer.
            return false;
        } else {
            return super.shouldDownloadInvoice(...arguments);
        }
    },
});
