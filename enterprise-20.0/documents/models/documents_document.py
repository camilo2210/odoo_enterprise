    def _get_access_vals_to_sync(self, documents):
        """Get action_update_access_rights `partners` / `group` to sync documents with self.

        :rtype: dict[int, tuple[str | bool, str | bool]]
        """
        self.ensure_one()
        assert self.type == "folder"
        members = self.access_ids.filtered(lambda a: a.role and (a.group_id or a.partner_id != self.owner_id.partner_id))
        partners = {self.owner_id.partner_id.id: ("edit", False)} if self.owner_id else {}
        partners.update({
            a.partner_id.id: (a.role, a.expiration_date)
            for a in members.filtered('partner_id')
        })
        groups = {
            a.group_id.id: (a.role, a.expiration_date)
            for a in members.filtered('group_id')
        }
        documents_and_descendants_members = self.env["documents.access"].sudo().search_fetch([
            ("role", "!=", False), ("document_id", "child_of", documents.ids)
        ], ["partner_id", "group_id"])
        partners.update({
            access.partner_id.id: (False, False)
            for access in documents_and_descendants_members
            if access.partner_id and access.partner_id.id not in partners
        })
        groups.update({
            access.group_id.id: (False, False)
            for access in documents_and_descendants_members
            if access.group_id and access.group_id.id not in groups
        })
        return partners, groups

